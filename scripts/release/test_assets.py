"""Exercise prepared reactor identity and complete GitHub draft publication."""

from contextlib import contextmanager
import json
import os
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch
import xml.etree.ElementTree as ET

import assets
import signing

ROOT = Path(__file__).resolve().parents[2]
TAG = "scylla-cdc-2.0.8"


class AssetTests(unittest.TestCase):
    @contextmanager
    def repository(self):
        original = Path.cwd()
        with tempfile.TemporaryDirectory() as temp:
            os.chdir(temp)
            try:
                def git(*args):
                    return subprocess.check_output(["git", "-c", "user.name=Test", "-c",
                        "user.email=test@example.invalid", "-c", "commit.gpgsign=false", "-c",
                        "tag.gpgSign=false", *args], stderr=subprocess.PIPE, text=True, timeout=30).strip()
                git("init", "--quiet")
                for name in ("pom.xml", *(module + "/pom.xml" for module in assets.MODULES)):
                    source = ET.parse(ROOT / name)
                    for path in ("m:version", "m:parent/m:version"):
                        version = source.find(path, assets.NS)
                        if version is not None:
                            version.text = "2.0.8"
                    Path(name).parent.mkdir(parents=True, exist_ok=True)
                    source.write(name)
                git("add", ".")
                git("commit", "--quiet", "-m", "Release")
                git("tag", "-a", "-m", "Release", TAG)
                git("tag", "scylla-cdc-99.99.99")
                # Current working POMs can be the next development iteration.
                Path("pom.xml").write_text((ROOT / "pom.xml").read_text())
                Path("release.properties").write_text("# Generated by Maven\nscm.tag=" + TAG + "\n"
                    "project.rel.com.scylladb\\:scylla-cdc=2.0.8\n")
                yield git
            finally:
                os.chdir(original)

    def test_prepared_identity_selects_four_tagged_binaries_despite_other_tags_and_working_version(self):
        with self.repository():
            self.assertEqual(assets.identity(), (TAG, "2.0.8"))
            self.assertEqual(list(map(str, assets.artifacts())), [
                "target/checkout/scylla-cdc-base/target/scylla-cdc-base-2.0.8.jar",
                "target/checkout/scylla-cdc-lib/target/scylla-cdc-lib-2.0.8.jar",
                "target/checkout/scylla-cdc-driver3/target/scylla-cdc-driver3-2.0.8.jar",
                "target/checkout/scylla-cdc-replicator/target/fat-jar/scylla-cdc-replicator-2.0.8-jar-with-dependencies.jar"])

    def test_identity_survives_maven_perform_cleanup(self):
        with self.repository(), patch.object(signing, "verify_prepared"):
            signing.save_prepared("trusted-baseline")
            Path("release.properties").unlink()
            self.assertEqual(assets.identity(), (TAG, "2.0.8"))

    def test_duplicate_malformed_inconsistent_or_missing_metadata_fails(self):
        with self.repository():
            original = Path("release.properties").read_text()
            for text in (original + "scm.tag=" + TAG + "\n", original.replace(TAG, "v2.0.8"),
                         original.replace(TAG, TAG + "-SNAPSHOT"), original.replace("=2.0.8", "=2.0.9"),
                         original.replace(TAG, "scylla-cdc-99.99.99"), "scm.tag=../../unsafe\n"):
                with self.subTest(text=text), self.assertRaises(signing.SigningError):
                    Path("release.properties").write_text(text)
                    assets.identity()

    def test_tagged_module_versions_and_packaging_are_checked(self):
        with self.repository(), patch.object(assets, "tagged_pom", wraps=assets.tagged_pom) as read:
            real = read._mock_wraps
            for field, value in (("m:parent/m:version", "99.0.1"), ("m:artifactId", "unexpected"),
                                 ("m:packaging", "war")):
                def changed(tag, path):
                    pom = real(tag, path)
                    if path == "scylla-cdc-replicator/pom.xml":
                        pom.find(field, assets.NS).text = value
                    return pom
                read.side_effect = changed
                with self.subTest(field=field), self.assertRaises(signing.SigningError):
                    assets.artifacts()

    def test_tagged_final_name_is_derived_and_unsafe_names_fail(self):
        with self.repository(), patch.object(assets, "tagged_pom", wraps=assets.tagged_pom) as read:
            real = read._mock_wraps
            name = "custom-${project.artifactId}-${project.version}"
            def changed(tag, path):
                pom = real(tag, path)
                if path == "scylla-cdc-base/pom.xml":
                    build = pom.find("m:build", assets.NS)
                    if build is None:
                        build = ET.SubElement(pom, "{" + assets.NS["m"] + "}build")
                    ET.SubElement(build, "{" + assets.NS['m'] + "}finalName").text = name
                return pom
            read.side_effect = changed
            self.assertEqual(assets.artifacts()[0].name, "custom-scylla-cdc-base-2.0.8.jar")
            for name in ("../../outside", "${unverified}"):
                with self.subTest(name=name), self.assertRaises(signing.SigningError):
                    assets.artifacts()

    @contextmanager
    def publication(self, mode="new"):
        with self.repository() as git:
            binaries = assets.artifacts()
            for path in binaries:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes((path.name + " binary").encode())
                Path(str(path) + ".asc").write_bytes((path.name + " signature").encode())
            all_files = [p for binary in binaries for p in (binary, Path(str(binary) + ".asc"))]
            state = {"draft": mode == "existing_draft", "published": mode == "existing_release",
                     "notes": "curated notes", "files": {"kept": b"existing"}, "calls": []}
            real_run = signing.run
            tag_sha = git("rev-parse", "refs/tags/" + TAG)

            def run(argv, *args, **kwargs):
                if argv[0] != "gh":
                    return real_run(argv, *args, **kwargs)
                state["calls"].append(argv)
                if argv[1:3] == ["api", "graphql"]:
                    if mode == "lookup_failure":
                        raise signing.SigningError("lookup failed")
                    if mode == "malformed_lookup": return "{}"
                    result = {"data": {"repository": {"release": {"id": "existing"}
                        if state["draft"] or state["published"] else None}}}
                    if mode == "graphql_error": result["errors"] = [{"message": "unavailable"}]
                    return json.dumps(result)
                if argv[1] == "api" and "/git/ref/tags/" in argv[2]:
                    return json.dumps({"object": {"type": "tag" if mode != "lightweight" else "commit",
                        "sha": tag_sha if mode != "moved_tag" else "a" * 40, "url": "unused"}})
                if argv[1] == "api" and "repos/{owner}/{repo}/releases/generate-notes" in argv:
                    self.assertIn("configuration_file_path=.github/release.yml", argv)
                    return json.dumps({"body": "filtered generated notes"})
                if argv[1:3] == ["release", "create"]:
                    self.assertIn("--draft", argv)
                    self.assertIn("--verify-tag", argv)
                    names = argv[4:argv.index("--verify-tag")]
                    self.assertEqual(names, list(map(str, all_files)))
                    self.assertEqual(kwargs["timeout"], 1800)
                    state.update(draft=True, files={Path(p).name: Path(p).read_bytes() for p in names},
                        notes=Path(argv[argv.index("--notes-file") + 1]).read_text())
                    if mode == "upload_failure":
                        state["files"].pop(all_files[-1].name)
                        raise signing.SigningError("upload failed")
                    return ""
                if argv[1:3] == ["release", "view"]:
                    reads = sum(call[1:3] == ["release", "view"] for call in state["calls"])
                    if mode == "missing_draft" or (mode == "delayed_view" and reads == 1):
                        raise signing.SigningError("Draft not yet visible")
                    return json.dumps({"databaseId": 7, "tagName": TAG, "isDraft": state["draft"]})
                if argv[1:4] == ["api", "--paginate", "--slurp"]:
                    listing = [{"name": name, "size": len(data), "state": "uploaded"}
                               for name, data in state["files"].items()]
                    if mode == "missing_asset": listing.pop()
                    if mode == "duplicate_asset": listing[-1] = listing[0]
                    if mode == "wrong_size": listing[-1]["size"] += 1
                    if mode == "pending_asset": listing[-1]["state"] = "new"
                    if mode == "asset_api_failure": raise signing.SigningError("asset API failed")
                    # Deliberately use multiple pages to check flattening.
                    return json.dumps([listing[:3], listing[3:]])
                if argv[1:3] == ["release", "download"]:
                    self.assertIn("--clobber", argv)
                    reads = sum(call[1:3] == ["release", "download"] for call in state["calls"])
                    if mode == "delayed_download" and reads == 1:
                        (Path(argv[-1]) / all_files[0].name).write_bytes(b"partial")
                        raise signing.SigningError("Draft download not yet visible")
                    for name, data in state["files"].items():
                        if mode == "incomplete_download" and name == all_files[-1].name: continue
                        if mode == "tampered_download" and name == all_files[-1].name: data = b"tampered"
                        (Path(argv[-1]) / name).write_bytes(data)
                    return ""
                if argv[1:3] == ["release", "edit"]:
                    self.assertEqual(argv[-1], "--draft=false")
                    if mode == "edit_failure": raise signing.SigningError("edit failed")
                    state.update(draft=False, published=True)
                    return ""
                raise AssertionError(argv)

            with patch.object(signing, "run", side_effect=run), \
                 patch.object(signing, "verify_prepared") as verify_history, \
                 patch.object(signing, "sign_files") as verify_files:
                if mode == "bad_signature": verify_files.side_effect = signing.SigningError("bad signature")
                if mode == "bad_history": verify_history.side_effect = signing.SigningError("bad history")
                yield state, all_files, verify_history, verify_files

    def test_publishes_only_after_verifying_all_eight_uploaded_assets(self):
        with self.publication() as (state, _, history, signatures):
            assets.publish()
            history.assert_called_once()
            signatures.assert_called_once()
            self.assertTrue(state["published"])
            self.assertFalse(state["draft"])
            self.assertEqual(len(state["files"]), 8)
            self.assertEqual(state["notes"], "filtered generated notes")
            operations = [call[2] for call in state["calls"]]
            self.assertLess(operations.index("download"), operations.index("edit"))

    def test_publication_streams_hashes_without_python_311_file_digest(self):
        with self.publication() as (state, files, _, _), \
                patch.object(assets.hashlib, "file_digest", None, create=True):
            files[0].write_bytes(b"multi-chunk binary" * 10000)
            assets.publish()
            self.assertTrue(state["published"])

    def test_delayed_draft_reads_retry_without_repeating_creation(self):
        for mode in ("delayed_view", "delayed_download", "missing_draft"):
            with self.subTest(mode=mode), self.publication(mode) as (state, _, _, _), \
                    patch.object(assets, "time") as clock:
                sleep = clock.sleep
                if mode == "missing_draft":
                    with self.assertRaises(signing.SigningError):
                        assets.publish()
                    self.assertFalse(state["published"])
                    self.assertTrue(state["draft"])
                    self.assertEqual(sleep.call_count, 2)
                else:
                    assets.publish()
                    self.assertTrue(state["published"])
                    sleep.assert_called_once_with(1)
                self.assertEqual(sum(call[1:3] == ["release", "create"]
                                     for call in state["calls"]), 1)

    def test_existing_releases_and_drafts_keep_assets_and_curated_notes(self):
        for mode in ("existing_release", "existing_draft"):
            with self.subTest(mode=mode), self.publication(mode) as (state, _, _, _):
                before = {key: state[key] for key in ("files", "notes", "draft", "published")}
                with self.assertRaisesRegex(signing.SigningError, "already exists"):
                    assets.publish()
                self.assertEqual({key: state[key] for key in before}, before)
                self.assertEqual(len(state["calls"]), 1)

    def test_invalid_signatures_history_and_missing_signatures_prevent_remote_writes(self):
        for mode in ("bad_signature", "bad_history", "missing_signature"):
            with self.subTest(mode=mode), self.publication(mode) as (state, files, _, _):
                if mode == "missing_signature": files[-1].unlink()
                with self.assertRaises(signing.SigningError): assets.publish()
                self.assertEqual(state["calls"], [])

    def test_failed_lookup_or_wrong_remote_tag_prevents_creation(self):
        for mode in ("lookup_failure", "malformed_lookup", "graphql_error", "moved_tag", "lightweight"):
            with self.subTest(mode=mode), self.publication(mode) as (state, _, _, _):
                with self.assertRaises(signing.SigningError): assets.publish()
                self.assertFalse(any(call[1:3] == ["release", "create"] for call in state["calls"]))

    def test_incomplete_or_tampered_uploads_remain_unpublished_for_manual_recovery(self):
        for mode in ("upload_failure", "missing_asset", "duplicate_asset", "wrong_size", "pending_asset",
                     "asset_api_failure", "incomplete_download", "tampered_download", "edit_failure"):
            with self.subTest(mode=mode), self.publication(mode) as (state, _, _, _):
                with self.assertRaises(signing.SigningError): assets.publish()
                self.assertTrue(state["draft"])
                self.assertFalse(state["published"])
                self.assertFalse(any("delete" in call for call in state["calls"]))


if __name__ == "__main__":
    unittest.main()
